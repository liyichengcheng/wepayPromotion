  async onLoad() {
    app.banCaptureScreen()
    let hasAccess = wx.getStorageSync("hasReadArticle")

    if (!hasAccess) {
      try {
        await app.waitLogin(5000)
        const res = await app.$request({
          url: "/pay/checkStatus",
          data: { articleId: app.globalData.articleId }
        })
        if (res.data.paid) {
          hasAccess = true
          wx.setStorageSync("hasReadArticle", true)
          app.globalData.isPayUnlock = true
        }
      } catch (e) {
        console.error("验证支付状态失败", e)
      }
    }

    if (!hasAccess) {
      wx.redirectTo({ url: "/pages/articlePreview/articlePreview" })
      return
    }

    const sysInfo = wx.getSystemInfoSync()
    const statusBarHeight = sysInfo.statusBarHeight || 20
    this.setData({ statusBarHeight })
    
    wx.showShareMenu({
      withShareTicket: true,
      menus: ['shareAppMessage', 'shareTimeline']
    })
  },

  onShow() {
    app.banCaptureScreen()
  },

  onUserCaptureScreen() {
    wx.showToast({
      title: '禁止截图，请尊重版权',
      icon: 'none',
      duration: 2000
    })
  },

  onReady() {
    const sysInfo = wx.getSystemInfoSync()
    const query = wx.createSelectorQuery()
    query.select('.chapter-list').boundingClientRect(rect => {
      if (rect) {
        const screenHeight = sysInfo.windowHeight
        const maxScroll = Math.max(rect.height - screenHeight + 200, 0)
        this.setData({ maxScroll })
      }
    }).exec()
  },

  onPageScroll(options) {
    if (this.data.maxScroll > 0) {
      const progress = Math.min(Math.round((options.scrollTop / this.data.maxScroll) * 100), 100)
      if (progress !== this.data.readProgress) {
        this.setData({ readProgress: progress })
      }
    }
  },

  preventCopy() {
    return false
  },

  toggleCatalog() {
    this.setData({ showCatalog: !this.data.showCatalog })
  },

  jumpToChapter(e) {
    const id = e.currentTarget.dataset.id
    this.setData({ showCatalog: false })
    wx.pageScrollTo({
      selector: '#chapter-' + id,
      duration: 300
    })
  },

  goBack() {
    const pages = getCurrentPages()
    if (pages.length > 1) {
      wx.navigateBack({ delta: 1 })
    } else {
      wx.redirectTo({ url: "/pages/articlePreview/articlePreview" })
    }
  },

  toIncomePage() {
    wx.navigateTo({ url: "/pages/shareIncome/shareIncome" })
  },

